def _show_polyscope(pts, normals, v_param, gt, methods):
    """Side-by-side panels: ground truth | jet | cnc | blow-up."""
    import polyscope as ps
    import polyscope.imgui as psim

    ps.init()
    ps.set_ground_plane_mode("shadow_only")

    method_names = list(methods.keys())
    bbox = pts.max(axis=0) - pts.min(axis=0)
    spacing = bbox[0] * 1.4

    ALL_QUANTITIES = QUANTITIES + [q + "_err" for q in QUANTITIES]

    # Compute error fields
    estimation_methods = [m for m in methods if m != "ground truth"]
    for mname in estimation_methods:
        for qname in QUANTITIES:
            methods[mname][qname + "_err"] = np.abs(
                methods[mname][qname] - gt[qname])
    for qname in QUANTITIES:
        gt[qname + "_err"] = np.zeros_like(gt[qname])

    # Shared colour ranges
    shared_range: dict[str, tuple[float, float]] = {}
    for qname in ALL_QUANTITIES:
        all_v = [methods[m][qname] for m in method_names if qname in methods[m]]
        if all_v:
            if qname in _POSITIVE_QUANTITIES:
                _, vmin, vmax = _clamp_positive(np.concatenate(all_v))
            else:
                _, vmin, vmax = _clamp(np.concatenate(all_v))
            shared_range[qname] = (vmin, vmax)
        else:
            shared_range[qname] = (-1.0, 1.0)

    panel_names: list[str] = []
    panel_data: dict[str, dict[tuple, tuple]] = {}
    for i, method in enumerate(method_names):
        offset = np.array([i * spacing, 0.0, 0.0])
        pname = f"torus/{method}"
        cloud = ps.register_point_cloud(pname, pts + offset, radius=0.001)
        cloud.set_color((0.75, 0.75, 0.75))
        panel_names.append(pname)
        panel_data[pname] = {}

        for qname in ALL_QUANTITIES:
            if qname not in methods[method]:
                continue
            raw = np.nan_to_num(methods[method][qname], nan=0.0)

            sv_min, sv_max = shared_range[qname]
            panel_data[pname][(qname, False)] = (
                np.clip(raw, sv_min, sv_max), sv_min, sv_max)

            if qname in _POSITIVE_QUANTITIES:
                _, pv_min, pv_max = _clamp_positive(methods[method][qname])
            else:
                _, pv_min, pv_max = _clamp(methods[method][qname])
            panel_data[pname][(qname, True)] = (
                np.clip(raw, pv_min, pv_max), pv_min, pv_max)

    # Initialise vmin/vmax from the first quantity's shared range
    _init_key = ("K", False)
    _init_vmin = _init_vmax = 0.0
    for _pn in panel_names:
        if _init_key in panel_data[_pn]:
            _, _init_vmin, _init_vmax = panel_data[_pn][_init_key]
            break

    state = {
        "quantity": 0, "normalize": False,
        "vmin": _init_vmin, "vmax": _init_vmax,
    }

    def _show_q(qname, normalize=False):
        key = (qname, normalize)
        cmap = CMAPS.get(qname, "viridis")
        if qname.endswith("_err"):
            cmap = CMAPS.get(qname, "Reds")
        vmin_o = state.get("vmin")
        vmax_o = state.get("vmax")
        for name in panel_names:
            if key in panel_data[name]:
                vals, vmin, vmax = panel_data[name][key]
                if vmin_o is not None:
                    vmin = vmin_o
                if vmax_o is not None:
                    vmax = vmax_o
                vals_clipped = np.clip(vals, vmin, vmax)
                ps.get_point_cloud(name).add_scalar_quantity(
                    "curvature", vals_clipped, enabled=True,
                    cmap=cmap, vminmax=(vmin, vmax))

    _show_q("K")

    def _refresh():
        _show_q(ALL_QUANTITIES[state["quantity"]], state["normalize"])

    def callback():
        psim.TextUnformatted(
            f"Torus (R={TORUS_R}, r={TORUS_r})  |  "
            f"Methods: {' | '.join(method_names)}")
        psim.Separator()

        changed_q, new_q = psim.Combo("Quantity", state["quantity"],
                                      ALL_QUANTITIES)
        if changed_q:
            state["quantity"] = new_q
            qname = ALL_QUANTITIES[new_q]
            key = (qname, state["normalize"])
            for _pn in panel_names:
                if key in panel_data[_pn]:
                    _, state["vmin"], state["vmax"] = panel_data[_pn][key]
                    break
            _refresh()

        changed_n, new_n = psim.Checkbox("Normalize per method",
                                         state["normalize"])
        if changed_n:
            state["normalize"] = new_n
            qname = ALL_QUANTITIES[state["quantity"]]
            key = (qname, new_n)
            for _pn in panel_names:
                if key in panel_data[_pn]:
                    _, state["vmin"], state["vmax"] = panel_data[_pn][key]
                    break
            _refresh()

        changed_vmin, new_vmin = psim.InputFloat("vmin", state["vmin"])
        changed_vmax, new_vmax = psim.InputFloat("vmax", state["vmax"])
        if changed_vmin or changed_vmax:
            state["vmin"] = new_vmin
            state["vmax"] = new_vmax
            _refresh()

        psim.Separator()
        if psim.Button("Export PLY"):
            _export_ply(pts, normals, panel_names, panel_data, state,
                        ALL_QUANTITIES)
        if psim.Button("Export colour bar"):
            _export_colourbar(panel_names, panel_data, state, ALL_QUANTITIES)
        if psim.Button("Export data (.npz)"):
            _export_data(v_param, gt, methods)
        if psim.Button("Screenshot"):
            fname = "torus_curvature.png"
            ps.screenshot(fname, transparent_bg=False)
            print(f"Saved {fname}")

    ps.set_user_callback(callback)
    ps.show()


