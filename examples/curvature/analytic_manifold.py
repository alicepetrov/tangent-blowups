def main():
    parser = argparse.ArgumentParser(
        description="Manifold curvature benchmark on the torus"
    )
    parser.add_argument("--k-bu", type=int, default=20, help="k-NN for blow-up")
    parser.add_argument("--n-max", type=int, default=None,
                        help="Downsample to at most this many points")
    parser.add_argument("--no-polyscope", action="store_true",
                        help="Skip polyscope viewer, only generate plots")
    args = parser.parse_args()

    print("\n=== Torus (manifold benchmark) ===")
    pts, normals, u_p, v_p = _load_pointcloud()
    n_total = len(pts)

    if args.n_max is not None and n_total > args.n_max:
        rng = np.random.default_rng(42)
        idx = rng.choice(n_total, args.n_max, replace=False)
        pts, normals, u_p, v_p = pts[idx], normals[idx], u_p[idx], v_p[idx]
        print(f"  {len(pts)} points (downsampled from {n_total})")
    else:
        print(f"  {len(pts)} points")

    # Ground truth
    print("  Computing analytic curvature ...")
    K_gt, H2_gt, total_gt = torus_analytic(u_p, v_p)
    gt = {"K": K_gt, "H2": H2_gt, "total": total_gt}

    # Blow-up
    print("  Computing blow-up curvature ...")
    bu = _blowup_curvature(pts, normals, k=args.k_bu)

    # Build methods dict in display order
    methods: dict[str, dict[str, np.ndarray]] = {"ground truth": gt}

    # Jet fitting baseline (pre-computed, from jet/ folder)
    jf = _load_jet_curvature("torus")
    if jf is not None:
        print(f"  Loading jet-fitting curvatures from jet/ ...")
        methods["jet"] = jf

    # CNC baseline (if file exists)
    cnc_path = Path(__file__).parent / "cnc" / "cnc_torus.txt"
    if cnc_path.exists():
        print(f"  Loading CNC curvatures from {cnc_path} ...")
        cnc_data = np.loadtxt(cnc_path)
        K_cnc = cnc_data[:, 0]
        H_cnc = cnc_data[:, 1]
        H2_cnc = H_cnc ** 2
        total_cnc = np.sqrt(np.maximum(4.0 * H2_cnc - 2.0 * K_cnc, 0.0))
        methods["cnc"] = {"K": K_cnc, "H2": H2_cnc, "total": total_cnc}
    else:
        print(f"  CNC file not found ({cnc_path}), skipping CNC baseline.")
        print(f"  To add it, run CNC on data/sampled_surfaces/torus_xyzn.txt")

    methods["blow-up"] = bu

    # Print correlations
    estimation_methods = [m for m in methods if m != "ground truth"]
    for qname in QUANTITIES:
        gt_v = gt[qname]
        for mname in estimation_methods:
            est_v = methods[mname][qname]
            mask = np.isfinite(gt_v) & np.isfinite(est_v)
            if mask.sum() > 3:
                r = np.corrcoef(gt_v[mask], est_v[mask])[0, 1]
                rmse = np.sqrt(np.mean((gt_v[mask] - est_v[mask]) ** 2))
                print(f"    {qname:>5s} {mname:>8s}: corr={r:.4f}  RMSE={rmse:.6f}")

    _print_summary_table(gt, methods)

    # Generate plots
    out_dir = Path(__file__).parent
    _plot_error_bar_chart(gt, methods, out_dir)
    _plot_error_histograms(gt, methods, out_dir)
    _plot_error_vs_v(v_p, gt, methods, out_dir)
    _plot_curvature_profile(v_p, gt, methods, out_dir)

    # Polyscope
    if not args.no_polyscope:
        _show_polyscope(pts, normals, v_p, gt, methods)


if __name__ == "__main__":
    main()
