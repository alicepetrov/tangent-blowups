"""
Curvature Estimation on Manifold Surfaces with Analytic Ground Truth
====================================================================
Benchmark on the torus (a smooth, closed manifold with no singularities)
to validate that all curvature estimators agree on well-behaved geometry.

Methods compared
----------------
1. **Ground truth** — K and H from the parametric fundamental forms.
2. **Blow-up** (ours) — level-1 iterated tangent blow-up.
3. **Jet fitting** (pre-computed, loaded from ``jet/`` folder).
4. **CNC** (pre-computed, loaded from ``cnc/`` folder).

Point-cloud files
-----------------
Generated by ``examples/io/sample_surfaces_to_txt.py``.  Format per line::

    x y z nx ny nz u v

Usage::

    python analytic_manifold.py
    python analytic_manifold.py --k-bu 25
    python analytic_manifold.py --no-polyscope       # plots only, no viewer
"""
