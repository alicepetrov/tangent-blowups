_PROFILE_LABELS = {
    "K": r"$K$",
    "H2": r"$H^2$",
    "total": r"$\|h\|$",
}


def _plot_curvature_profile(v_param, gt, methods, out_dir: Path, n_bins=60):
    """Top row: curvature vs v with analytic curve.  Bottom row: |error|."""
    plt.rcParams.update({
        "font.family": "serif",
        "font.size": 8.5,
        "axes.labelsize": 9,
        "axes.titlesize": 10,
        "legend.fontsize": 7.5,
        "xtick.labelsize": 7.5,
        "ytick.labelsize": 7.5,
        "figure.dpi": 200,
    })

    estimation_methods = [m for m in methods if m != "ground truth"]
    n_q = len(QUANTITIES)
    fig, axes = plt.subplots(2, n_q, figsize=(2.8 * n_q, 4.4),
                             gridspec_kw={"height_ratios": [1.3, 1]})

    # Pre-compute analytic curves on a fine grid
    v_fine = np.linspace(0, 2 * np.pi, 500)
    gt_fine_K, gt_fine_H2, gt_fine_total = torus_analytic(
        np.zeros_like(v_fine), v_fine)
    gt_fine = {"K": gt_fine_K, "H2": gt_fine_H2, "total": gt_fine_total}

    # Bin edges and centres for the scatter data
    bin_edges = np.linspace(0, 2 * np.pi, n_bins + 1)
    bin_centres = 0.5 * (bin_edges[:-1] + bin_edges[1:])

    def _bin_stats(values, v_vals):
        mask = np.isfinite(values) & np.isfinite(v_vals)
        vv, ee = v_vals[mask], values[mask]
        idx = np.clip(np.digitize(vv, bin_edges) - 1, 0, n_bins - 1)
        med = np.full(n_bins, np.nan)
        q25 = np.full(n_bins, np.nan)
        q75 = np.full(n_bins, np.nan)
        for i in range(n_bins):
            sel = ee[idx == i]
            if len(sel) > 2:
                med[i] = np.median(sel)
                q25[i] = np.percentile(sel, 25)
                q75[i] = np.percentile(sel, 75)
        return med, q25, q75

    v_ticks = [0, np.pi / 2, np.pi, 3 * np.pi / 2, 2 * np.pi]
    v_tick_labels = ["0", r"$\pi/2$", r"$\pi$", r"$3\pi/2$", r"$2\pi$"]

    for col, qname in enumerate(QUANTITIES):
        ax_top = axes[0, col]
        ax_bot = axes[1, col]
        gt_vals = gt[qname]

        # --- Top row: curvature profile ---
        ax_top.plot(v_fine, gt_fine[qname], color="k", lw=1.4, ls="-",
                    label="analytic", zorder=10)

        for mname in estimation_methods:
            est = methods[mname][qname]
            sty = _METHOD_STYLE.get(mname, {})
            color = sty.get("color")
            med, q25, q75 = _bin_stats(est, v_param)
            ax_top.fill_between(bin_centres, q25, q75, alpha=0.15,
                                color=color, linewidth=0)
            ax_top.plot(bin_centres, med,
                        marker=sty.get("marker", "o"), markersize=2.5,
                        ls="none", color=color, label=mname, zorder=5)

        ax_top.set_title(_QUANTITY_TITLES.get(qname, qname))
        # y-label only on leftmost column
        if col == 0:
            ax_top.set_ylabel(_PROFILE_LABELS.get(qname, qname))
        else:
            ax_top.set_ylabel("")
        ax_top.set_xlim(0, 2 * np.pi)
        ax_top.set_xticks(v_ticks)
        ax_top.set_xticklabels([])
        ax_top.spines["top"].set_visible(False)
        ax_top.spines["right"].set_visible(False)
        ax_top.grid(True, alpha=0.2, lw=0.5)

        # --- Bottom row: absolute error ---
        for mname in estimation_methods:
            est = methods[mname][qname]
            err = np.abs(est - gt_vals)
            sty = _METHOD_STYLE.get(mname, {})
            color = sty.get("color")
            med, q25, q75 = _bin_stats(err, v_param)
            ax_bot.fill_between(bin_centres, q25, q75, alpha=0.12,
                                color=color, linewidth=0)
            ax_bot.plot(bin_centres, med,
                        marker=sty.get("marker", "o"), markersize=2.5,
                        ls=sty.get("ls", "-"), lw=sty.get("lw", 1.0),
                        color=color, label=mname)

        # x-label only on middle column
        if col == n_q // 2:
            ax_bot.set_xlabel(r"poloidal angle $v$")
        else:
            ax_bot.set_xlabel("")
        # y-label only on leftmost column
        if col == 0:
            ax_bot.set_ylabel("absolute error")
        else:
            ax_bot.set_ylabel("")
        ax_bot.set_yscale("log")
        ax_bot.set_xlim(0, 2 * np.pi)
        ax_bot.set_xticks(v_ticks)
        ax_bot.set_xticklabels(v_tick_labels)
        ax_bot.yaxis.set_major_locator(ticker.LogLocator(base=10, numticks=5))
        ax_bot.yaxis.set_minor_formatter(ticker.NullFormatter())
        ax_bot.spines["top"].set_visible(False)
        ax_bot.spines["right"].set_visible(False)
        ax_bot.grid(True, which="major", alpha=0.2, lw=0.5)

    # Single legend in top-right panel
    handles, labels = axes[0, -1].get_legend_handles_labels()
    axes[0, -1].legend(handles, labels, frameon=True, fancybox=False,
                       edgecolor="0.8", loc="upper right")

    fig.tight_layout(h_pad=0.4, w_pad=1.2)
    fname = out_dir / "torus_curvature_profile.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"  Saved {fname}")
    plt.show()


