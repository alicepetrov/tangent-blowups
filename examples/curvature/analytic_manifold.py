def _load_pointcloud():
    """Load (pts, normals, u, v) from the torus text file."""
    path = _pointcloud_dir() / "torus.txt"
    if not path.exists():
        raise FileNotFoundError(
            f"Point cloud not found: {path}\n"
            "Run  examples/io/sample_surfaces_to_txt.py  first."
        )
    data = np.loadtxt(path)
    pts = data[:, :3]
    nrm = data[:, 3:6]
    u = data[:, 6]
    v = data[:, 7]

    valid = (
        np.isfinite(pts).all(1)
        & np.isfinite(nrm).all(1)
        & (np.linalg.norm(nrm, axis=1) > 1e-8)
    )
    nrm = normalize_vectors(nrm)
    return pts[valid], nrm[valid], u[valid], v[valid]


# =====================================================================
# Analytic curvature for the torus
# =====================================================================

TORUS_R, TORUS_r = 2.0, 1.0


def torus_analytic(u, v, R=TORUS_R, r=TORUS_r):
    """Analytic Gaussian and mean curvature of the torus.

    K = cos(v) / (r * (R + r*cos(v)))
    H = (R + 2*r*cos(v)) / (2*r * (R + r*cos(v)))
    """
    u, v = np.asarray(u, float), np.asarray(v, float)
    cv = np.cos(v)
    denom = r * (R + r * cv)
    K = cv / denom
    H = (R + 2.0 * r * cv) / (2.0 * denom)
    H2 = H ** 2
    total = np.sqrt(np.maximum(4.0 * H2 - 2.0 * K, 0.0))
    return K, H2, total


