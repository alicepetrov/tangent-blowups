def _plot_error_histograms(gt, methods, out_dir: Path):
    """Per-quantity error histograms comparing all methods."""
    plt.rcParams.update({
        "font.family": "serif",
        "font.size": 9,
        "axes.labelsize": 10,
        "axes.titlesize": 11,
        "legend.fontsize": 8.5,
        "xtick.labelsize": 8,
        "ytick.labelsize": 8,
        "figure.dpi": 150,
    })

    estimation_methods = [m for m in methods if m != "ground truth"]
    n_q = len(QUANTITIES)
    fig, axes = plt.subplots(1, n_q, figsize=(3.25 * n_q, 2.6), sharey=False)

    for col, (ax, qname) in enumerate(zip(axes, QUANTITIES)):
        gt_vals = gt[qname]
        for mname in estimation_methods:
            est = methods[mname][qname]
            err = np.abs(est - gt_vals)
            mask = np.isfinite(err) & np.isfinite(gt_vals) & (err > 0)
            if mask.sum() < 10:
                continue
            sty = _METHOD_STYLE.get(mname, {})
            ax.hist(np.log10(err[mask]), bins=60, alpha=0.45,
                    color=sty.get("color"), label=mname, density=True)

        if col == n_q // 2:
            ax.set_xlabel(r"$\log_{10}$ |error|")
        else:
            ax.set_xlabel("")
        if col == 0:
            ax.set_ylabel("density")
        else:
            ax.set_ylabel("")
        ax.set_title(_QUANTITY_TITLES.get(qname, qname))
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.grid(True, which="major", alpha=0.25, lw=0.6)

    axes[-1].legend(frameon=True, fancybox=False, edgecolor="0.8",
                    loc="upper left")
    fig.tight_layout(w_pad=1.8)
    fname = out_dir / "torus_error_histograms.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"  Saved {fname}")
    plt.show()


