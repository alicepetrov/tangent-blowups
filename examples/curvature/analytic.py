def _plot_error_vs_distance(sing_dist, gt, methods, surface_name,
                            singularity_label, n_bins=25):
    import matplotlib.pyplot as plt
    import matplotlib.ticker as ticker

    plt.rcParams.update({
        "font.family": "serif",
        "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
        "mathtext.fontset": "cm",
        "font.size": 9,
        "axes.labelsize": 10,
        "axes.titlesize": 11,
        "legend.fontsize": 8.5,
        "xtick.labelsize": 8,
        "ytick.labelsize": 8,
        "figure.dpi": 150,
    })

    estimation_methods = [m for m in methods if m != "ground truth"]
    n_q = len(QUANTITIES)
    fig, axes = plt.subplots(1, n_q, figsize=(3.25 * n_q, 2.6), sharey=False)

    for col, (ax, qname) in enumerate(zip(axes, QUANTITIES)):
        gt_vals = gt[qname]
        for mname in estimation_methods:
            est = methods[mname][qname]
            err = np.abs(est - gt_vals)

            mask = np.isfinite(err) & np.isfinite(sing_dist) & np.isfinite(gt_vals)
            d, e = sing_dist[mask], err[mask]
            if len(d) < 10:
                continue

            bin_edges = np.linspace(d.min(), d.max(), n_bins + 1)
            bin_centres = 0.5 * (bin_edges[:-1] + bin_edges[1:])
            bin_idx = np.clip(np.digitize(d, bin_edges) - 1, 0, n_bins - 1)

            medians = np.array([
                np.median(e[bin_idx == i]) if np.sum(bin_idx == i) > 0
                else np.nan
                for i in range(n_bins)
            ])
            q25 = np.array([
                np.percentile(e[bin_idx == i], 25) if np.sum(bin_idx == i) > 2
                else np.nan
                for i in range(n_bins)
            ])
            q75 = np.array([
                np.percentile(e[bin_idx == i], 75) if np.sum(bin_idx == i) > 2
                else np.nan
                for i in range(n_bins)
            ])

            sty = _METHOD_STYLE.get(mname, {})
            color = sty.get("color", None)
            ax.fill_between(bin_centres, q25, q75, alpha=0.12, color=color,
                            linewidth=0)
            ax.plot(bin_centres, medians, label=mname,
                    marker=sty.get("marker", "o"), markersize=3,
                    ls=sty.get("ls", "-"), lw=sty.get("lw", 1.2),
                    color=color)

        # x-axis label only on the middle panel
        if col == n_q // 2:
            ax.set_xlabel(singularity_label)
        else:
            ax.set_xlabel("")

        # y-axis label only on the leftmost panel
        if col == 0:
            ax.set_ylabel("absolute error")
        else:
            ax.set_ylabel("")

        ax.set_title(_QUANTITY_TITLES.get(qname, qname))
        ax.set_yscale("log")
        # Fixed evenly-spaced log ticks
        ax.yaxis.set_major_locator(ticker.LogLocator(base=10, numticks=5))
        ax.yaxis.set_minor_formatter(ticker.NullFormatter())
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.grid(True, which="major", alpha=0.25, lw=0.6)

    axes[-1].legend(frameon=True, fancybox=False, edgecolor="0.8",
                    loc="upper right")

    fig.tight_layout(w_pad=1.8)
    fname = f"error_vs_singularity_{surface_name}.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"  Saved {fname}")
    plt.show()


def _plot_error_bar_chart(all_results):
    """Grouped bar chart: median absolute error per method per quantity per surface."""
    import matplotlib.pyplot as plt

    plt.rcParams.update({
        "font.family": "serif",
        "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
        "mathtext.fontset": "cm",
        "font.size": 9,
        "axes.labelsize": 10,
        "axes.titlesize": 11,
        "legend.fontsize": 8.5,
        "xtick.labelsize": 8,
        "ytick.labelsize": 8,
        "figure.dpi": 150,
    })

    # Collect (surface, method, quantity) -> median |error|
    rows = []
    for res in all_results:
        gt = res["gt"]
        estimation_methods = [m for m in res["methods"] if m != "ground truth"]
        for mname in estimation_methods:
            for qname in QUANTITIES:
                gt_v = gt[qname]
                est_v = res["methods"][mname][qname]
                mask = np.isfinite(gt_v) & np.isfinite(est_v)
                if mask.sum() < 3:
                    continue
                mae = np.median(np.abs(gt_v[mask] - est_v[mask]))
                rows.append((res["surface_name"], mname, qname, mae))

    if not rows:
        print("  No data for bar chart.")
        return

    surfaces = list(dict.fromkeys(r[0] for r in rows))
    methods = list(dict.fromkeys(r[1] for r in rows))
    n_surfaces = len(surfaces)
    n_methods = len(methods)
    n_quantities = len(QUANTITIES)

    # One group of bars per (surface, quantity); bars within group = methods
    n_groups = n_surfaces * n_quantities
    group_labels = [f"{s}\n{q}" for s in surfaces for q in QUANTITIES]

    x = np.arange(n_groups)
    bar_width = 0.8 / n_methods

    fig, ax = plt.subplots(figsize=(max(8, 2 * n_groups), 5))
    for j, method in enumerate(methods):
        vals = []
        for s in surfaces:
            for q in QUANTITIES:
                match = [r[3] for r in rows
                         if r[0] == s and r[1] == method and r[2] == q]
                vals.append(match[0] if match else 0.0)
        ax.bar(x + j * bar_width, vals, bar_width, label=method)

    ax.set_xticks(x + bar_width * (n_methods - 1) / 2)
    ax.set_xticklabels(group_labels)
    ax.set_ylabel("median |error|")
    ax.set_title("Curvature estimation error (all surfaces / methods / quantities)")
    ax.legend()
    ax.set_yscale("log")
    ax.grid(True, axis="y", alpha=0.3)

    plt.tight_layout()
    fname = "curvature_error_bar_chart.pdf"
    fig.savefig(fname, bbox_inches="tight")
