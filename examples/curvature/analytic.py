# Analytic curvature formulae
# =====================================================================

def _fundamental_forms(dpdu, dpdv, dpuu, dpuv, dpvv):
    """(K, H) from parametric first/second fundamental forms."""
    E = np.sum(dpdu * dpdu, axis=-1)
    F = np.sum(dpdu * dpdv, axis=-1)
    G = np.sum(dpdv * dpdv, axis=-1)

    n_raw = np.cross(dpdu, dpdv)
    n_norm = np.linalg.norm(n_raw, axis=-1, keepdims=True)
    n_norm = np.where(n_norm > 1e-15, n_norm, 1.0)
    n_hat = n_raw / n_norm

    L = np.sum(dpuu * n_hat, axis=-1)
    M = np.sum(dpuv * n_hat, axis=-1)
    N_ = np.sum(dpvv * n_hat, axis=-1)

    det_I = E * G - F * F
    det_I = np.where(np.abs(det_I) > 1e-30, det_I, np.nan)

    K = (L * N_ - M * M) / det_I
    H = (E * N_ - 2.0 * F * M + G * L) / (2.0 * det_I)
    return K, H


def whitney_analytic(u, v, scale=1.0):
    s = scale
    u, v = np.asarray(u, float), np.asarray(v, float)
    dpdu = np.stack([s * v, np.full_like(u, s), np.zeros_like(u)], axis=-1)
    dpdv = np.stack([s * u, np.zeros_like(u), 2.0 * s * v], axis=-1)
    dpuu = np.zeros_like(dpdu)
    dpuv = np.stack([np.full_like(u, s), np.zeros_like(u),
                     np.zeros_like(u)], axis=-1)
    dpvv = np.stack([np.zeros_like(u), np.zeros_like(u),
                     np.full_like(u, 2.0 * s)], axis=-1)
    K, H = _fundamental_forms(dpdu, dpdv, dpuu, dpuv, dpvv)
    H2 = H ** 2
    total = np.sqrt(np.maximum(4.0 * H2 - 2.0 * K, 0.0))
    return K, H2, total


KLEIN_RADIUS, KLEIN_SCALE = 2.0, 1.0


def klein_analytic(u, v, radius=KLEIN_RADIUS, scale=KLEIN_SCALE):
    u, v = np.asarray(u, float), np.asarray(v, float)
    cu, su = np.cos(u), np.sin(u)
    cuh, suh = np.cos(0.5 * u), np.sin(0.5 * u)
    sv, cv = np.sin(v), np.cos(v)
    s2v, c2v = np.sin(2.0 * v), np.cos(2.0 * v)

    a = radius + cuh * sv - suh * s2v
    dadu = -0.5 * (suh * sv + cuh * s2v)
    dadv = cuh * cv - 2.0 * suh * c2v
    daduu = -0.25 * (cuh * sv - suh * s2v)
    daduv = -0.5 * (suh * cv + 2.0 * cuh * c2v)
    dadvv = -cuh * sv + 4.0 * suh * s2v

    dpdu = scale * np.stack([
        dadu * cu - a * su,
        dadu * su + a * cu,
        0.5 * (cuh * sv - suh * s2v),
    ], axis=-1)
    dpdv = scale * np.stack([
        dadv * cu, dadv * su,
        suh * cv + 2.0 * cuh * c2v,
    ], axis=-1)
    dpuu = scale * np.stack([
        daduu * cu - 2.0 * dadu * su - a * cu,
        daduu * su + 2.0 * dadu * cu - a * su,
        0.25 * (-suh * sv - cuh * s2v),
    ], axis=-1)
    dpuv = scale * np.stack([
        daduv * cu - dadv * su,
        daduv * su + dadv * cu,
        0.5 * (cuh * cv - 2.0 * suh * c2v),
    ], axis=-1)
    dpvv = scale * np.stack([
        dadvv * cu, dadvv * su,
        -suh * sv - 4.0 * cuh * s2v,
    ], axis=-1)

    K, H = _fundamental_forms(dpdu, dpdv, dpuu, dpuv, dpvv)
    H2 = H ** 2
    total = np.sqrt(np.maximum(4.0 * H2 - 2.0 * K, 0.0))
    return K, H2, total


# =====================================================================
# Singularity distance
# =====================================================================

def _whitney_singularity_distance(u, v, pts):
    """Distance from the pinch-point singularity line (u = 0)."""
    return np.abs(u)


def _klein_self_intersection_distance(u, v, pts, k=120):
    """Ambient distance to the nearest self-intersection point.

    For each point, find k spatial nearest neighbours and pick the
    closest one whose *parameter-space* distance (on the [0,2pi]^2
    torus) exceeds pi/2.  Small values flag points near the
    self-intersection curve.
    """
    from scipy.spatial import cKDTree

    tree = cKDTree(pts)
    dists, idx = tree.query(pts, k=k + 1)  # +1 because self is included
    # drop self
    dists, idx = dists[:, 1:], idx[:, 1:]

    # periodic parameter distance on [0, 2pi]^2
    du = np.abs(u[:, None] - u[idx])
    du = np.minimum(du, 2.0 * np.pi - du)
    dv = np.abs(v[:, None] - v[idx])
    dv = np.minimum(dv, 2.0 * np.pi - dv)
    param_dist = np.sqrt(du ** 2 + dv ** 2)

    # mask neighbours that are parametrically close (same sheet)
    far_in_param = param_dist > np.pi / 2.0
    dists_far = np.where(far_in_param, dists, np.inf)
    min_dist = dists_far.min(axis=1)
    return min_dist


