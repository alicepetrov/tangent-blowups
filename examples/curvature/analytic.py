"""
Curvature Estimation on Parametric Surfaces with Analytic Ground Truth
======================================================================
Side-by-side comparison of curvature estimation methods on the Whitney
umbrella and Klein bottle, loaded from pre-sampled text files so that
every method is evaluated on the exact same point cloud.

Methods compared
----------------
1. **Ground truth** — K and H² from the parametric fundamental forms.
2. **Blow-up** (ours) — level-1 iterated tangent blow-up.
3. **Jet fitting** (pre-computed, loaded from ``jet/`` folder).
4. **CNC** (pre-computed, loaded from ``cnc/`` folder).

Point-cloud files
-----------------
Generated by ``examples/io/sample_surfaces_to_txt.py``.  Format per line::

    x y z nx ny nz u v

The ``u v`` columns are the parametric coordinates used for ground truth.

Usage::

    python analytic.py                       # both surfaces
    python analytic.py -s whitney            # Whitney umbrella only
    python analytic.py -s klein              # Klein bottle only
    python analytic.py --k-bu 25             # custom k-NN
"""
