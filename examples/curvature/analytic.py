def _clamp(vals, pct=5):
    finite = vals[np.isfinite(vals)]
    if len(finite) == 0:
        return np.nan_to_num(vals, nan=0.0), -1.0, 1.0
    lo, hi = np.percentile(finite, [pct, 100 - pct])
    vmax = max(abs(lo), abs(hi), 1e-15)
    clamped = np.clip(np.nan_to_num(vals, nan=0.0), -vmax, vmax)
    return clamped, -vmax, vmax


def _clamp_positive(vals, pct=5):
    finite = vals[np.isfinite(vals)]
    if len(finite) == 0:
        return np.nan_to_num(vals, nan=0.0), 0.0, 1.0
    hi = np.percentile(finite, 100 - pct)
    hi = max(hi, 1e-15)
    clamped = np.clip(np.nan_to_num(vals, nan=0.0), 0.0, hi)
    return clamped, 0.0, hi


def _show_quantity(qname, panel_names, panel_data, *, normalize=False,
                   vmin_override=None, vmax_override=None):
    key = (qname, normalize)
    cmap = CMAPS.get(qname, "viridis")
    for name in panel_names:
        if key in panel_data[name]:
            vals, vmin, vmax = panel_data[name][key]
            if vmin_override is not None:
                vmin = vmin_override
            if vmax_override is not None:
                vmax = vmax_override
            vals_clipped = np.clip(vals, vmin, vmax)
            ps.get_point_cloud(name).add_scalar_quantity(
                "curvature", vals_clipped, enabled=True,
                cmap=cmap, vminmax=(vmin, vmax),
            )


