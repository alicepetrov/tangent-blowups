# Summary table
# =====================================================================

def _print_summary_table(gt, methods):
    """Print a LaTeX-ready table of median absolute errors and correlations."""
    estimation_methods = [m for m in methods if m != "ground truth"]

    print("\n  %-10s" % "", end="")
    for qname in QUANTITIES:
        print(f"  {'MAE ' + qname:>12s}  {'corr ' + qname:>12s}", end="")
    print()

    for mname in estimation_methods:
        print(f"  {mname:10s}", end="")
        for qname in QUANTITIES:
            gt_v = gt[qname]
            est_v = methods[mname][qname]
            mask = np.isfinite(gt_v) & np.isfinite(est_v)
            if mask.sum() < 3:
                print(f"  {'---':>12s}  {'---':>12s}", end="")
                continue
            mae = np.median(np.abs(gt_v[mask] - est_v[mask]))
            r = np.corrcoef(gt_v[mask], est_v[mask])[0, 1]
            print(f"  {mae:12.6f}  {r:12.6f}", end="")
        print()

    # LaTeX table
    print("\n  % LaTeX table (paste into paper):")
    print(r"  \begin{tabular}{lccc}")
    print(r"    \toprule")
    print(r"    Method & $K$ & $H^2$ & $\|h\|$ \\")
    print(r"    \midrule")
    for mname in estimation_methods:
        row = f"    {mname}"
        for qname in QUANTITIES:
            gt_v = gt[qname]
            est_v = methods[mname][qname]
            mask = np.isfinite(gt_v) & np.isfinite(est_v)
            if mask.sum() < 3:
                row += " & ---"
                continue
            mae = np.median(np.abs(gt_v[mask] - est_v[mask]))
            row += f" & {mae:.2e}"
        row += r" \\"
        print(row)
    print(r"    \bottomrule")
    print(r"  \end{tabular}")


# =====================================================================
# Core runner
# =====================================================================

def run(
    surface_name: str,
    *,
    k_bu: int = 20,
    n_max: int | None = None,
    y_offset: float = 0.0,
):
    cfg = SURFACES[surface_name]

    print(f"\n=== {surface_name} ===")
    pts, normals, u_p, v_p = _load_pointcloud(surface_name)
    n_total = len(pts)

    if n_max is not None and n_total > n_max:
        rng = np.random.default_rng(42)
        idx = rng.choice(n_total, n_max, replace=False)
        pts, normals, u_p, v_p = pts[idx], normals[idx], u_p[idx], v_p[idx]
        print(f"  {len(pts)} points (downsampled from {n_total})")
    else:
        print(f"  {len(pts)} points")

    # Ground truth
    print("  Computing analytic curvature ...")
    K_gt, H2_gt, total_gt = cfg["analytic"](u_p, v_p)

    # Mask singular region where analytic curvature diverges
    if cfg["singular_mask_fn"] is not None:
        singular = cfg["singular_mask_fn"](u_p, v_p)
        K_gt[singular] = np.nan
        H2_gt[singular] = np.nan
        total_gt[singular] = np.nan

    gt = {"K": K_gt, "H2": H2_gt, "total": total_gt}

    # Blow-up
    print("  Computing blow-up curvature ...")
    bu = _blowup_curvature(pts, normals, k=k_bu)

    # Build methods dict in display order: ground truth -> jet -> cnc -> blow-up
    methods: dict[str, dict[str, np.ndarray]] = {"ground truth": gt}

    # Jet fitting baseline (pre-computed, from jet/ folder)
    jf = _load_jet_curvature(surface_name)
    if jf is not None:
        print(f"  Loading jet-fitting curvatures from jet/ ...")
        methods["jet"] = jf

    # CNC baseline (if file exists)
    cnc_path = Path(__file__).parent / "cnc" / f"cnc_{surface_name}.txt"
    if cnc_path.exists():
        print(f"  Loading CNC curvatures from {cnc_path} ...")
        cnc_data = np.loadtxt(cnc_path)
        K_cnc = cnc_data[:, 0]
        H_cnc = cnc_data[:, 1]
        H2_cnc = H_cnc ** 2
        total_cnc = np.sqrt(np.maximum(4.0 * H2_cnc - 2.0 * K_cnc, 0.0))
        methods["cnc"] = {"K": K_cnc, "H2": H2_cnc, "total": total_cnc}

    methods["blow-up"] = bu

    # Singularity distance
    print("  Computing singularity distance ...")
    sing_dist = cfg["singularity_distance"](u_p, v_p, pts)

    # Print correlations
    estimation_methods = [m for m in methods if m != "ground truth"]
    for qname in QUANTITIES:
        gt_v = gt[qname]
        for mname in estimation_methods:
            est_v = methods[mname][qname]
            mask = np.isfinite(gt_v) & np.isfinite(est_v)
            if mask.sum() > 3:
                r = np.corrcoef(gt_v[mask], est_v[mask])[0, 1]
                rmse = np.sqrt(np.mean((gt_v[mask] - est_v[mask]) ** 2))
                print(f"    {qname:>3s} {mname:>8s}: corr={r:.4f}  RMSE={rmse:.4f}")

    _print_summary_table(gt, methods)

    # -- Compute error fields --
    for mname in estimation_methods:
        for qname in QUANTITIES:
            methods[mname][qname + "_err"] = np.abs(
                methods[mname][qname] - gt[qname])
    for qname in QUANTITIES:
        gt[qname + "_err"] = np.zeros_like(gt[qname])

    # -- Polyscope panels --
    method_names = list(methods.keys())
    bbox = pts.max(axis=0) - pts.min(axis=0)
    spacing = bbox[0] * 1.4

    # Shared colour ranges
    shared_range: dict[str, tuple[float, float]] = {}
    for qname in ALL_QUANTITIES:
        all_v = [methods[m][qname] for m in method_names if qname in methods[m]]
        if all_v:
            if qname in _POSITIVE_QUANTITIES:
                _, vmin, vmax = _clamp_positive(np.concatenate(all_v))
            else:
                _, vmin, vmax = _clamp(np.concatenate(all_v))
            shared_range[qname] = (vmin, vmax)
        else:
            shared_range[qname] = (-1.0, 1.0)

    panel_names: list[str] = []
    panel_data: dict[str, dict[tuple, tuple]] = {}
    for i, method in enumerate(method_names):
        offset = np.array([i * spacing, y_offset, 0.0])
        pname = f"{surface_name}/{method}"
        cloud = ps.register_point_cloud(pname, pts + offset, radius=0.001)
        cloud.set_color((0.75, 0.75, 0.75))
        cloud.add_vector_quantity("normals", normals, enabled=False,
                                 color=(0.2, 0.2, 0.8))
        panel_names.append(pname)
        panel_data[pname] = {}

        for qname in ALL_QUANTITIES:
            if qname not in methods[method]:
                continue
            raw = np.nan_to_num(methods[method][qname], nan=0.0)

            sv_min, sv_max = shared_range[qname]
            panel_data[pname][(qname, False)] = (
                np.clip(raw, sv_min, sv_max), sv_min, sv_max)

            if qname in _POSITIVE_QUANTITIES:
                _, pv_min, pv_max = _clamp_positive(methods[method][qname])
            else:
                _, pv_min, pv_max = _clamp(methods[method][qname])
            panel_data[pname][(qname, True)] = (
                np.clip(raw, pv_min, pv_max), pv_min, pv_max)

    return dict(
        method_names=method_names,
        panel_names=panel_names,
        panel_data=panel_data,
        pts=pts,
        normals=normals,
        gt=gt,
        methods=methods,
        sing_dist=sing_dist,
        singularity_label=cfg["singularity_label"],
        surface_name=surface_name,
    )


