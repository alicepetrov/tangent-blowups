# Main
# =====================================================================

def main():
    parser = argparse.ArgumentParser(
        description="Curvature estimation vs analytic ground truth"
    )
    parser.add_argument(
        "-s", "--surface", type=str, default=None,
        choices=list(SURFACES.keys()),
        help="Surface to visualise (default: both)",
    )
    parser.add_argument("--k-bu", type=int, default=20, help="k-NN for blow-up")
    parser.add_argument("--n-max", type=int, default=None,
                        help="Downsample to at most this many points")
    args = parser.parse_args()

    surface_names = [args.surface] if args.surface else list(SURFACES.keys())

    ps.init()
    ps.set_ground_plane_mode("shadow_only")

    all_panel_names: list[str] = []
    all_panel_data: dict[str, dict] = {}
    all_results: list[dict] = []

    for idx, sname in enumerate(surface_names):
        result = run(sname, k_bu=args.k_bu,
                     n_max=args.n_max,
                     y_offset=idx * 8.0)
        all_panel_names.extend(result["panel_names"])
        all_panel_data.update(result["panel_data"])
        all_results.append(result)

    # Initialise vmin/vmax from the first quantity's shared range
    _init_key = ("K", False)
    _init_vmin = _init_vmax = 0.0
    for _pn in all_panel_names:
        if _init_key in all_panel_data[_pn]:
            _, _init_vmin, _init_vmax = all_panel_data[_pn][_init_key]
            break

    state = {
        "quantity": 0, "normalize": False, "normals": False,
        "vmin": _init_vmin, "vmax": _init_vmax,
    }

    _show_quantity("K", all_panel_names, all_panel_data, normalize=False,
                   vmin_override=state["vmin"], vmax_override=state["vmax"])

    def _refresh():
        _show_quantity(ALL_QUANTITIES[state["quantity"]], all_panel_names,
                       all_panel_data, normalize=state["normalize"],
                       vmin_override=state["vmin"],
                       vmax_override=state["vmax"])

    def callback():
        psim.TextUnformatted(
            f"Surfaces: {', '.join(surface_names)}  |  "
            f"Methods: {' | '.join(all_results[0]['method_names'])}"
        )
        psim.Separator()

        changed_q, new_q = psim.Combo("Quantity", state["quantity"],
                                      ALL_QUANTITIES)
        if changed_q:
            state["quantity"] = new_q
            # Reset vmin/vmax to defaults for the new quantity
            qname = ALL_QUANTITIES[new_q]
            key = (qname, state["normalize"])
            for _pn in all_panel_names:
                if key in all_panel_data[_pn]:
                    _, state["vmin"], state["vmax"] = all_panel_data[_pn][key]
                    break
            _refresh()

        changed_n, new_n = psim.Checkbox("Normalize per method",
                                         state["normalize"])
        if changed_n:
            state["normalize"] = new_n
            qname = ALL_QUANTITIES[state["quantity"]]
            key = (qname, new_n)
            for _pn in all_panel_names:
                if key in all_panel_data[_pn]:
                    _, state["vmin"], state["vmax"] = all_panel_data[_pn][key]
                    break
            _refresh()

        changed_vmin, new_vmin = psim.InputFloat("vmin", state["vmin"])
        changed_vmax, new_vmax = psim.InputFloat("vmax", state["vmax"])
        if changed_vmin or changed_vmax:
            state["vmin"] = new_vmin
            state["vmax"] = new_vmax
            _refresh()

        changed_nrm, new_nrm = psim.Checkbox("Show normals", state["normals"])
        if changed_nrm:
            state["normals"] = new_nrm
            for res in all_results:
                for pname in res["panel_names"]:
                    ps.get_point_cloud(pname).add_vector_quantity(
                        "normals", res["normals"], enabled=new_nrm,
                        color=(0.2, 0.2, 0.8))

        psim.Separator()

        for res in all_results:
            label = f"Error vs singularity ({res['surface_name']})"
            if psim.Button(label):
                _plot_error_vs_distance(
                    res["sing_dist"], res["gt"], res["methods"],
                    res["surface_name"], res["singularity_label"],
                )

        if psim.Button("Error bar chart (all surfaces)"):
            _plot_error_bar_chart(all_results)

        psim.Separator()

        for res in all_results:
            sn = res["surface_name"]
            if psim.Button(f"Export PLY ({sn})"):
                _export_ply(sn, res["pts"], res["normals"],
                            res["panel_names"], all_panel_data, state)
            if psim.Button(f"Export colour bar ({sn})"):
                _export_colourbar(sn, res["panel_names"], all_panel_data, state)

        if psim.Button("Export data (.npz)"):
            _export_data(all_results)

        if psim.Button("Screenshot"):
            fname = "curvature_analytic.png"
            ps.screenshot(fname, transparent_bg=False)
            print(f"Saved {fname}")

    ps.set_user_callback(callback)
    ps.show()


if __name__ == "__main__":
    main()
