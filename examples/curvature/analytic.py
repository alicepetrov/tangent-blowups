def _load_pointcloud(name: str):
    """Load (pts, normals, u, v) from the text file."""
    path = _pointcloud_dir() / f"{name}.txt"
    if not path.exists():
        raise FileNotFoundError(
            f"Point cloud not found: {path}\n"
            "Run  examples/io/sample_surfaces_to_txt.py  first."
        )
    data = np.loadtxt(path)
    pts = data[:, :3]
    nrm = data[:, 3:6]
    u = data[:, 6]
    v = data[:, 7]

    valid = (
        np.isfinite(pts).all(1)
        & np.isfinite(nrm).all(1)
        & (np.linalg.norm(nrm, axis=1) > 1e-8)
    )
    nrm = normalize_vectors(nrm)
    return pts[valid], nrm[valid], u[valid], v[valid]


